import Foundation

/// Во что превращается бюджет шагов на конкретном приложении.
///
/// Тип живёт в ядре, а не рядом со сканером, по одной причине: сканеру нужен
/// симулятор, поэтому всё, что в нём написано, проверить тестом нельзя. Именно
/// это однажды стоило дорого — правка в файл сканера молча не применилась
/// и несколько заходов подряд считалась сделанной. Всё, что можно посчитать
/// без симулятора, вынесено сюда и покрыто тестами; в сканере остаются только
/// нажатия.
public enum WalkStrategy: Equatable {

    /// У приложения есть вкладки: идём вширь по ним, затем вглубь внутри них.
    /// - breadth: подписи вкладок, которые успеваем обойти
    /// - depth: вкладки, внутрь которых успеваем спуститься на уровень
    case tabs(breadth: [String], depth: [String])

    /// Вкладок нет: открываем строки списка по номеру, каждый раз возвращаясь.
    case list(cellIndices: [Int])
}

public enum WalkPlanner {

    /// Распределяет бюджет шагов между шириной и глубиной.
    ///
    /// - Parameters:
    ///   - tabs: подписи вкладок, пустой массив если вкладок нет
    ///   - cellCount: сколько строк списка видно в корне
    ///   - budget: сколько ВСЕГО экранов разрешено снять, включая стартовый
    ///
    /// Стартовый экран снимается всегда и занимает один шаг бюджета, поэтому
    /// на переходы остаётся `budget - 1`. Он нужен даже при наличии вкладок:
    /// замер показал, что в «Фото» стартовый экран — это 49 элементов,
    /// а вкладка «Медиатека» после нажатия — 13, то есть разные экраны;
    /// а в «Здоровье» стартовый экран вообще единственный достижимый.
    ///
    /// Ширина идёт перед глубиной сознательно. Нажатие вкладки надёжно
    /// и не зависит от содержимого, а спуск вглубь зависит и срывается чаще.
    /// Если бюджета не хватает, терять правильнее глубину.
    public static func plan(tabs: [String], cellCount: Int, budget: Int) -> WalkStrategy {
        let forNavigation = max(0, budget - 1)

        guard !tabs.isEmpty else {
            return .list(cellIndices: Array(0..<min(max(0, cellCount), forNavigation)))
        }

        let breadth = Array(tabs.prefix(forNavigation))
        let left = max(0, forNavigation - breadth.count)
        return .tabs(breadth: breadth, depth: Array(tabs.prefix(left)))
    }
}
