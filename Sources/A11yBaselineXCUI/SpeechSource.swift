import Foundation
import A11yBaselineCore

/// Источник реплик: то, что умеет пройти по приложению и сказать, что
/// произносится на каждом элементе.
///
/// Абстракция существует ровно по одной причине, и она не архитектурная,
/// а календарная. До iOS 27 получить реальную речь VoiceOver из теста было
/// нельзя, и все инструменты приближали её, собирая строку из дерева
/// доступности. С iOS 27 появился `XCUIVoiceOverService`, который возвращает
/// произнесённое напрямую. Обе реализации нужны одновременно: первая работает
/// везде уже сегодня, вторая точнее, но требует свежего Xcode.
///
/// Всё, что выше по стеку — правила, диффер, отчёты — не знает, какой источник
/// использовался, кроме одного места: базовая линия помечается признаком
/// точности, и сравнивать линии с разной точностью запрещено.
@MainActor
public protocol SpeechSource {

    /// Чем снято. Попадает в базовую линию.
    var fidelity: CaptureFidelity { get }

    /// Готовит источник к обходу.
    func begin() throws

    /// Снимает реплики текущего экрана в порядке обхода.
    func captureScreen(named name: String) throws -> ScreenSnapshot

    /// Завершает обход и возвращает систему в исходное состояние.
    func end() throws
}
